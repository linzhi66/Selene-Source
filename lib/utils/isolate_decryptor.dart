  /// AES-128 CBC 解密（无填充）
  ///
  /// [encrypted] - 加密数据
  /// [key] - 16 字节密钥
  /// [iv] - 16 字节 IV
  static Uint8List decryptAes128Cbc(
    List<int> encrypted,
    List<int> key,
    List<int> iv,
  ) {
    if (key.length != 16) {
      throw ArgumentError('Key must be 16 bytes for AES-128');
    }
    if (iv.length != 16) {
      throw ArgumentError('IV must be 16 bytes');
    }
    if (encrypted.length % 16 != 0) {
      throw ArgumentError('Encrypted data length must be multiple of 16');
    }

    // 生成轮密钥
    final roundKeys = _keyExpansion(key);

    // 解密
    final result = Uint8List(encrypted.length);
    var previousBlock = Uint8List.fromList(iv);

    for (var i = 0; i < encrypted.length; i += 16) {
      final block = Uint8List(16);
      for (var j = 0; j < 16; j++) {
        block[j] = encrypted[i + j];
      }

      // 解密块
      final decryptedBlock = _decryptBlock(block, roundKeys);

      // XOR with previous block (CBC mode)
      for (var j = 0; j < 16; j++) {
        result[i + j] = decryptedBlock[j] ^ previousBlock[j];
      }

      // 保存当前加密块作为下一个块的 previousBlock
      previousBlock = Uint8List.fromList(block);
    }

    return result;
  }

  /// 解密单个块
  static Uint8List _decryptBlock(Uint8List block, List<Uint8List> roundKeys) {
    final state = Uint8List.fromList(block);

    // 初始轮密钥加
    _addRoundKey(state, roundKeys[10]);

    // 9 轮迭代
    for (var round = 9; round > 0; round--) {
      _invShiftRows(state);
      _invSubBytes(state);
      _addRoundKey(state, roundKeys[round]);
      _invMixColumns(state);
    }

    // 最后一轮
    _invShiftRows(state);
    _invSubBytes(state);
    _addRoundKey(state, roundKeys[0]);

    return state;
  }

  /// 密钥扩展
  static List<Uint8List> _keyExpansion(List<int> key) {
    final roundKeys = <Uint8List>[];
    var temp = Uint8List(4);

    // 初始密钥
    for (var i = 0; i < 4; i++) {
      roundKeys.add(Uint8List.fromList([
        key[i * 4],
        key[i * 4 + 1],
        key[i * 4 + 2],
        key[i * 4 + 3],
      ]));
    }

    // 生成其余轮密钥
    for (var i = 4; i < 44; i++) {
      temp = Uint8List.fromList(roundKeys[i - 1]);

      if (i % 4 == 0) {
        // RotWord
        final t = temp[0];
        temp[0] = temp[1];
        temp[1] = temp[2];
        temp[2] = temp[3];
        temp[3] = t;

        // SubWord
        for (var j = 0; j < 4; j++) {
          temp[j] = _sBox[temp[j]];
        }

        // XOR with RCon
        temp[0] ^= _rCon[(i ~/ 4) - 1];
      }

      final newWord = Uint8List(4);
      for (var j = 0; j < 4; j++) {
        newWord[j] = roundKeys[i - 4][j] ^ temp[j];
      }
      roundKeys.add(newWord);
    }

    // 将 44 个 word 转换为 11 个 16 字节轮密钥
    final result = <Uint8List>[];
    for (var i = 0; i < 11; i++) {
      final roundKey = Uint8List(16);
      for (var j = 0; j < 4; j++) {
        for (var k = 0; k < 4; k++) {
          roundKey[j * 4 + k] = roundKeys[i * 4 + j][k];
        }
      }
      result.add(roundKey);
    }

    return result;
  }

  /// 轮密钥加
  static void _addRoundKey(Uint8List state, Uint8List roundKey) {
    for (var i = 0; i < 16; i++) {
      state[i] ^= roundKey[i];
    }
  }

  /// 逆字节替换
  static void _invSubBytes(Uint8List state) {
    for (var i = 0; i < 16; i++) {
      state[i] = _invSBox[state[i]];
    }
  }

  /// 逆行移位
  static void _invShiftRows(Uint8List state) {
    final temp = Uint8List(16);

    // Row 0: 不移位
    temp[0] = state[0];
    temp[4] = state[4];
    temp[8] = state[8];
    temp[12] = state[12];

    // Row 1: 右移 1 位
    temp[1] = state[13];
    temp[5] = state[1];
    temp[9] = state[5];
    temp[13] = state[9];

    // Row 2: 右移 2 位
    temp[2] = state[10];
    temp[6] = state[14];
    temp[10] = state[2];
    temp[14] = state[6];

    // Row 3: 右移 3 位
    temp[3] = state[7];
    temp[7] = state[11];
    temp[11] = state[15];
    temp[15] = state[3];

    for (var i = 0; i < 16; i++) {
      state[i] = temp[i];
    }
  }

  /// 逆列混淆
  static void _invMixColumns(Uint8List state) {
    for (var i = 0; i < 4; i++) {
      final s0 = state[i * 4];
      final s1 = state[i * 4 + 1];
      final s2 = state[i * 4 + 2];
      final s3 = state[i * 4 + 3];

      state[i * 4] = _multiply(0x0e, s0) ^
          _multiply(0x0b, s1) ^
          _multiply(0x0d, s2) ^
          _multiply(0x09, s3);
      state[i * 4 + 1] = _multiply(0x09, s0) ^
          _multiply(0x0e, s1) ^
          _multiply(0x0b, s2) ^
          _multiply(0x0d, s3);
      state[i * 4 + 2] = _multiply(0x0d, s0) ^
          _multiply(0x09, s1) ^
          _multiply(0x0e, s2) ^
          _multiply(0x0b, s3);
      state[i * 4 + 3] = _multiply(0x0b, s0) ^
          _multiply(0x0d, s1) ^
          _multiply(0x09, s2) ^
          _multiply(0x0e, s3);
    }
  }

  /// GF(2^8) 乘法
  static int _multiply(int a, int b) {
    var result = 0;
    var aa = a;
    var bb = b;

    for (var i = 0; i < 8; i++) {
      if ((bb & 1) != 0) {
        result ^= aa;
      }
      final highBit = aa & 0x80;
      aa <<= 1;
      if (highBit != 0) {
        aa ^= 0x1b; // AES 不可约多项式
      }
      bb >>= 1;
    }

    return result & 0xFF;
  }
